#!/usr/bin/env node
/**
 * Встраивает шрифты ридера в styles.css как @font-face с data: URI.
 *
 * Зачем data: URI, а не url("fonts/…"): Obsidian подключает styles.css плагина
 * как встроенный стиль, поэтому относительные пути резолвятся от корня приложения,
 * а не от папки плагина. Data URI работает без сети и без правок на стороне Obsidian.
 *
 * Источники: Google Fonts (OFL 1.1), файлы лежат в fonts/, лицензии рядом.
 * Запуск: node scripts/build-fonts.mjs
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const fontsDir = join(root, "fonts");
const stylesPath = join(root, "styles.css");

// Диапазоны те же, что отдаёт Google Fonts в css2, чтобы кириллица и латиница
// не перекрывали друг друга в одном семействе.
const UNICODE_RANGES = {
  latin: "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+2074, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD",
  "latin-ext": "U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF",
  cyrillic: "U+0301, U+0400-045F, U+0490-0491, U+04B0-04B1, U+2116",
  "cyrillic-ext": "U+0460-052F, U+1C80-1C8A, U+20B4, U+2DE0-2DFF, U+A640-A69F, U+FE2E-FE2F",
};

const FACES = [
  { family: "Golos Text", cssName: "Golos Text", weight: 400, files: ["golos-text-400-cyrillic", "golos-text-400-cyrillic-ext", "golos-text-400-latin", "golos-text-400-latin-ext"] },
  { family: "Golos Text", cssName: "Golos Text", weight: 600, files: ["golos-text-600-cyrillic", "golos-text-600-cyrillic-ext", "golos-text-600-latin", "golos-text-600-latin-ext"] },
  { family: "Atkinson Hyperlegible", cssName: "Atkinson Hyperlegible", weight: 400, files: ["atkinson-hyperlegible-400-latin", "atkinson-hyperlegible-400-latin-ext"] },
];

const START = "/* >>> reader fonts (generated by scripts/build-fonts.mjs) */";
const END = "/* <<< reader fonts */";

let block = START + "\n";
for (const face of FACES) {
  for (const base of face.files) {
    const file = join(fontsDir, base + ".woff2");
    if (!existsSync(file)) {
      console.error(`нет файла шрифта: ${file}`);
      process.exit(1);
    }
    const subsetKey = base.endsWith("-cyrillic-ext") ? "cyrillic-ext"
      : base.endsWith("-cyrillic") ? "cyrillic"
      : base.endsWith("-latin-ext") ? "latin-ext"
      : "latin";
    const data = readFileSync(file).toString("base64");
    block += `@font-face {\n  font-family: "${face.cssName}";\n  font-style: normal;\n  font-weight: ${face.weight};\n  font-display: swap;\n  src: url(data:font/woff2;base64,${data}) format("woff2");\n  unicode-range: ${UNICODE_RANGES[subsetKey]};\n}\n`;
  }
}

block += `
.sr-modal-container.sr-font-golos .sr-word-box,
.sr-modal-container.sr-font-golos .sr-chunk-word,
.sr-modal-container.sr-font-golos .sr-context-preview {
  font-family: "Golos Text", var(--font-text);
}

.sr-modal-container.sr-font-atkinson .sr-word-box,
.sr-modal-container.sr-font-atkinson .sr-chunk-word,
.sr-modal-container.sr-font-atkinson .sr-context-preview {
  font-family: "Atkinson Hyperlegible", var(--font-text);
}
` + END + "\n";

const css = readFileSync(stylesPath, "utf8");
const withoutOld = css.includes(START)
  ? css.slice(0, css.indexOf(START)) + css.slice(css.indexOf(END) + END.length + 1)
  : css;
writeFileSync(stylesPath, withoutOld.trimEnd() + "\n\n" + block);
console.log(`styles.css: добавлено ${FACES.reduce((n, f) => n + f.files.length, 0)} @font-face, итого ${readFileSync(stylesPath).length} байт`);
